import ollama
from llm_core.rag_engine import _get_embedding_model
from llm_core.context_builder import build_context

# Expose _get_embedding_model for compatibility with vector_memory
__all__ = ["_get_embedding_model", "SmartBrain", "panda_brain", "_is_question"]

# Config and Ollama client
_OLLAMA_URL = os.getenv("OLLAMA_URL", "http://localhost:11434")
_MODEL_NAME = os.getenv("MODEL_NAME", "llama3.1:8b")
_ollama_client = ollama.Client(
    host=_OLLAMA_URL,
    timeout=120.0,
    headers={"ngrok-skip-browser-warning": "true"}
)

class SmartBrain:
    def __init__(self):
        pass
    def process(self, user_input):
        return None

def _is_question(user_input, has_conversation_history=False):
    return False

def panda_brain(user_input, context_from_rag="", conversation_history=None, session_id=None):
    """
    Streams conversational reply from Ollama using context generated by context_builder.
    """
    messages, token_limit, temperature = build_context(
        user_input, 
        context_from_rag=context_from_rag, 
        conversation_history=conversation_history, 
        session_id=session_id
    )
    
    response = _ollama_client.chat(
        model=_MODEL_NAME,
        messages=messages,
        stream=True,
        options={
            "num_predict": token_limit,
            "temperature": temperature,
        },
    )

    for chunk in response:
        yield chunk['message']['content']
